import catalogue from '../data/catalogue.json'; // generated by scripts/build-catalogue.mjs

export type ProductOption = { id: string; name: string; priceAdjustment: number; description: string };
export type SetOption = { id: string; name: string; price: number };
export type SizeOption = { size: number; bookable: boolean };
export type ProductStatus = 'Avbl' | 'Sold' | 'Photos Missing';

export type Product = {
  id: string;
  slug: string;
  identifier: string; // sheet Article number, e.g. "101"
  websiteName: string; // "101 | Lavender Mul A Line ..."
  name: string;
  description: string;
  category: string;
  status: ProductStatus;
  available: boolean;
  images: string[];
  color: string;
  fabric: string;
  silhouette: string;
  pattern: string;
  dyeable: boolean;
  length: string;
  size: string; // raw sheet value: "NA", "Freesize" or "38 | 40"
  sizes: SizeOption[]; // [] when size is NA / Freesize, else every size 38-44 with a bookable flag
  mrp: number;
  basePrice: number; // price of the first set option
  setOptions: SetOption[]; // sheet "Set Option 1/2" with "Price Option 1/2"
  tags: string[];
  options: ProductOption[]; // add-ons
};

// Every size offered. A sized product lists all of them; only the sizes in the sheet are bookable.
export const SIZE_RANGE = [38, 40, 42, 44] as const;

const toSizes = (raw: string): SizeOption[] => {
  const value = raw.trim();
  if (!value || /^na$/i.test(value) || /free/i.test(value)) return [];
  const have = value.split('|').map((s) => parseInt(s.trim(), 10));
  return SIZE_RANGE.map((size) => ({ size, bookable: have.includes(size) }));
};

const ADD_ONS: ProductOption[] = [
  { id: 'matching-inner', name: 'Add a matching inner', priceAdjustment: 300, description: 'An optional finishing touch for your order.' },
  { id: 'gift-wrap', name: 'Gift wrap', priceAdjustment: 150, description: 'An optional finishing touch for your order.' },
];

const DESCRIPTION = 'A considered piece from the Rumi Studio collection. Contact us on WhatsApp for sizing and availability details.';

type Row = Omit<Product, 'description' | 'sizes' | 'basePrice' | 'tags' | 'options'>;

export const products: Product[] = (catalogue as unknown as Row[]).map((row) => ({
  ...row,
  description: DESCRIPTION,
  sizes: toSizes(row.size),
  basePrice: row.setOptions[0]?.price ?? row.mrp,
  tags: [],
  options: ADD_ONS,
}));

export const formatPrice = (amount: number) => new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', maximumFractionDigits: 0 }).format(amount);

// Old slugs that should still resolve: { 'old-slug': 'new-slug' }
export const productSlugAliases: Record<string, string> = {};

export const getProduct = (slug: string) => products.find((product) => product.slug === (productSlugAliases[slug] ?? slug));

// Optional 3rd arg picks a set option (e.g. "kurta-dupatta-bottom"); defaults to the first set.
export const productUnitPrice = (product: Product, optionIds: string[], setOptionId?: string) => {
  const base = product.setOptions.find((s) => s.id === setOptionId)?.price ?? product.basePrice;
  return base + product.options.filter((option) => optionIds.includes(option.id)).reduce((sum, option) => sum + option.priceAdjustment, 0);
};

// [] means NA / Freesize (no picker), otherwise 38-44 with bookable flags.
export const getSizes = (product: Product) => product.sizes;
export const isSizeBookable = (product: Product, size: number) => product.sizes.find((s) => s.size === size)?.bookable ?? false;

// "You may also like": same identifier first, then same category, then same fabric, then anything live.
// Sold pieces and pieces without photos are skipped.
export const RELATED_LIMIT = 4;
export const getRelatedProducts = (product: Product, limit = RELATED_LIMIT): Product[] => {
  const pool = products.filter((p) => p.id !== product.id && p.available && p.images.length > 0);
  const picked = new Map<string, Product>();
  const take = (list: Product[]) => list.forEach((p) => picked.size < limit && picked.set(p.id, p));
  take(pool.filter((p) => p.identifier === product.identifier));
  take(pool.filter((p) => p.category === product.category));
  take(pool.filter((p) => p.fabric === product.fabric));
  take(pool);
  return [...picked.values()];
};